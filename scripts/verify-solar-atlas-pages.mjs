import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import http from 'node:http';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { queryEnvironment } from '../solar-atlas/src/environment.js';
import { createPreview } from './preview.mjs';

const workspace = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(workspace, 'solar-atlas', 'output');
await fs.mkdir(output, { recursive: true });
await import('./build-solar-atlas-site.mjs');
const preview = createPreview();
const server = http.createServer((req, res) => {
  if (!req.url.startsWith('/-3D/')) { res.writeHead(404); res.end(); return; }
  req.url = req.url.slice('/-3D'.length);
  preview.emit('request', req, res);
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${server.address().port}/-3D/solar-atlas/`;
let browser;
const errors = [], missing = [], unexpectedAPI = [];
try {
  const weatherFixture = { current: { time: new Date().toISOString().slice(0, 16), temperature_2m: 22, relative_humidity_2m: 67, precipitation: 0, wind_speed_10m: 3.2, wind_direction_10m: 125 }, current_units: { temperature_2m: '°C', relative_humidity_2m: '%', precipitation: 'mm', wind_speed_10m: 'm/s' } };
  const wrapped = await queryEnvironment('weather', { lat: 39.9, lon: 116.4 }, { transport: 'direct', fetch: async url => { assert.match(url, /^https:\/\/api\.open-meteo\.com\//); return new Response(JSON.stringify(weatherFixture)); } });
  assert.equal(wrapped.source, 'Open-Meteo');
  await assert.rejects(queryEnvironment('weather', { lat: NaN, lon: 0 }), /有效范围/);
  browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-webgl', '--ignore-gpu-blocklist', '--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.url().startsWith(base) && response.status() >= 400) missing.push({ url: response.url(), status: response.status() }); });
  page.on('request', request => { if (request.url().includes('/api/weather') || request.url().includes('/api/solar-wind')) unexpectedAPI.push(request.url()); });
  await page.goto(base, { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => window.solarAtlas?.state.ready, { timeout: 60000 });
  await page.locator('#landing').waitFor({ state: 'visible' });
  assert.equal(await page.evaluate(() => SOLAR_ATLAS_CONFIG.dataTransport), 'direct');
  await page.locator('#enter-atlas').tap();
  await page.locator('[role=tab][data-mode=three]').tap();
  assert.equal(await page.evaluate(() => solarAtlas.state.mode), 'three');
  await page.locator('#open-search').tap();
  await page.locator('#search-input').fill('地球');
  await page.locator('#search-results [role=option]').first().tap();
  await page.locator('.ocean-gateway').tap();
  await page.locator('[data-ocean-panel=views]').tap();
  await page.locator('[data-globe-layer=currents]').tap();
  await page.locator('#close-panel').tap();
  await page.screenshot({ path: path.join(output, 'pages-mobile-ocean.png'), animations: 'disabled' });
  await page.route('https://api.open-meteo.com/**', route => route.fulfill({ status: 200, contentType: 'application/json', headers: { 'Access-Control-Allow-Origin': '*' }, body: JSON.stringify(weatherFixture) }));
  await page.locator('[data-ocean-panel=weather]').tap();
  await page.getByText('已获得带有效时间的气象数据', { exact: true }).waitFor();
  assert.match(await page.locator('#weather-result').innerText(), /22 °C/);
  await page.screenshot({ path: path.join(output, 'pages-mobile-weather.png'), animations: 'disabled' });
  await page.locator('#close-panel').tap();
  await page.locator('#back-solar').tap();
  await page.reload();
  await page.waitForFunction(() => window.solarAtlas?.state.ready, { timeout: 60000 });
  await page.locator('#archive').waitFor({ state: 'visible' });
  assert.equal(await page.evaluate(() => solarAtlas.state.selection.id), 'earth');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), 390);
  assert.deepEqual(unexpectedAPI, [], 'Static deployment must not call Node-only API routes.');
  assert.deepEqual(errors, []);
  assert.deepEqual(missing, []);
  const html = await (await fetch(base)).text();
  assert(html.includes('./config.js'));
  for (const file of ['server.mjs', 'package.json', 'scripts/verify.mjs', 'output/server.json']) assert.equal((await fetch(new URL(file, base))).status, 404);
  await fs.writeFile(path.join(output, 'pages-verification.json'), JSON.stringify({ passed: true, checkedAt: new Date().toISOString(), basePath: '/-3D/solar-atlas/', checks: ['static build allowlist', 'GitHub project subpath', '390px touch navigation', 'Earth and ocean gateway', 'direct weather transport', 'URL restore', 'no local API calls', 'no missing assets or runtime errors'], errors, missing, unexpectedAPI }, null, 2));
  console.log('PASS · Pages subpath, mobile touch, ocean, direct weather, URL restore, static allowlist and no runtime errors.');
} finally { if (browser) await browser.close(); await new Promise(resolve => server.close(resolve)); }
